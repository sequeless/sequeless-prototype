-- Marks the signal rows that the drain left unprocessed (spec 13, step P4; DR-26 (written with this change)).
-- Flyway applies this once, at app start. It runs after the old version has drained the SignalReceived rows,
-- and after the owner's O-3 count, the deploy step that must show zero unprocessed rows of each claimed kind
-- before the new version starts. This statement is the backstop for any row that the count missed.
-- It stamps only the SignalReceived kind; the rows of every other kind keep processed_at NULL.
--
-- Marked, not dispatched: P4 removes the signal kind from the code (DR-26), so no version that runs this
-- migration has a handler for it. The P4 code runs a signal's transition in the request that accepts it, so
-- no SignalReceived row is written from then on. A signal row still unprocessed here is a signal that returned
-- 202 whose transition never ran. It is marked without dispatch, so its transition does not run and leaves no
-- record.
--
-- Dead-lettered SignalReceived rows (V7) keep processed_at NULL, so this statement stamps them too, as V8 stamps
-- dead-lettered ActionRequest rows and V9 stamps dead-lettered timer rows (P4 plan, OQ11: decided).
UPDATE sq_outbox SET processed_at = now() WHERE kind = 'SignalReceived' AND processed_at IS NULL;
